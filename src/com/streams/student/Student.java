package com.streams.student;

public class Student {
	
	private String name;
	
	private Double percentage;

	public String getName() {
		return name;
	}

	public Double getPercentage() {
		return percentage;
	}

	public Student(String name, Double percentage) {
		super();
		this.name = name;
		this.percentage = percentage;
	}
	
	

}
